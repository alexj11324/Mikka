import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import test from 'node:test'
import { Pool } from 'pg'

// Explicitly refuse business databases. This executes the real server action and real SQL.
const target = new URL(process.env.E2E_DATABASE_URL ?? 'http://invalid')
if (!['localhost', '127.0.0.1', '[::1]'].includes(target.hostname) || !target.pathname.endsWith('_e2e') || process.env.MIKKA_DATABASE_URL !== target.href || process.env.DATABASE_URL !== target.href) throw new Error('Run summary integration requires the same isolated loopback *_e2e database for both stores')
const pool = new Pool({ connectionString: target.href, max: 1 })
const owner = randomUUID(), viewer = randomUUID(), outsider = randomUUID(), removed = randomUUID()
const issue = randomUUID(), other = randomUUID(), workspace = randomUUID(), team = randomUUID(), agent = randomUUID()
const run = randomUUID(), removedRun = randomUUID(), otherRun = randomUUID()
const excessRuns = Array.from({ length: 21 }, () => randomUUID())
test('real action enforces membership, issue boundaries, removal, bounded field whitelist and owner-only output/controls', async () => {
  const { listIssueRunSummaries } = await import('../app/actions/agents')
  const { actAs } = await import('../lib/acting-user')
  const { readRun, addRunMessage, requestRunStop } = await import('../lib/agent-runs')
  try {
    for (const id of [owner, viewer, outsider, removed]) await pool.query('INSERT INTO "user" (id, name, email, "emailVerified", "createdAt", "updatedAt") VALUES ($1,$2,$3,false,now(),now())', [id, 'Isolated run test', `${id}@example.com`])
    for (const id of [issue, other]) await pool.query(`INSERT INTO issues (id,"userId",title,content,status,priority) VALUES ($1,$2,$3,'{"type":"doc","content":[]}','todo','normal')`, [id, owner, 'Isolated safe summary'])
    await pool.query('INSERT INTO issue_members ("issueId","userId","memberId") VALUES ($1,$2,$3),($1,$2,$4)', [issue, owner, viewer, removed])
    await pool.query('INSERT INTO agents (id,"userId",harness,name,instructions) VALUES ($1,$2,$3,$4,$5)', [agent,owner,'codex','PRIVATE NAME','PRIVATE INSTRUCTIONS'])
    for (const [id, userId, issueId] of [[run,owner,issue],[removedRun,removed,issue],[otherRun,owner,other]]) await pool.query('INSERT INTO agent_runs (id,"userId","issueId","agentId",status,prompt,report,error) VALUES ($1,$2,$3,$4,$5,$6,$7,$8)', [id,userId,issueId,agent,'running','PRIVATE PROMPT',JSON.stringify({secret:'PRIVATE REPORT'}),'PRIVATE ERROR'])
    await pool.query('INSERT INTO run_chunks (id,"runId",seq,chunk) VALUES ($1,$2,1,$3)', [randomUUID(),run,JSON.stringify({type:'text-delta',delta:'PRIVATE OUTPUT'})])
    await assert.rejects(actAs(outsider, () => listIssueRunSummaries(issue)))
    await assert.rejects(actAs(viewer, () => listIssueRunSummaries(other)))
    await assert.rejects(actAs(viewer, () => listIssueRunSummaries('invalid')))
    const summaries = await actAs(viewer, () => listIssueRunSummaries(issue))
    assert.equal(summaries.length,2)
    assert.ok(summaries.every(row => row.id !== otherRun && !row.ownedByCurrentUser))
    for (const row of summaries) assert.deepEqual(Object.keys(row).sort(),['id','status','createdAt','updatedAt','ownedByCurrentUser'].sort())
    assert.ok(!JSON.stringify(summaries).includes('PRIVATE'))
    assert.equal(await readRun(viewer,run),null)
    await assert.rejects(addRunMessage(viewer,{runId:run,text:'Must not reach owner'}))
    await requestRunStop(viewer,run)
    const {rows:[unchanged]} = await pool.query('SELECT "stopRequestedAt" FROM agent_runs WHERE id=$1',[run])
    assert.equal(unchanged.stopRequestedAt,null)
    assert.ok(await readRun(owner,run))
    await pool.query('DELETE FROM issue_members WHERE "issueId"=$1 AND "memberId"=$2',[issue,removed])
    assert.deepEqual((await actAs(viewer,()=>listIssueRunSummaries(issue))).map(row=>row.id),[run])
    await assert.rejects(actAs(removed,()=>listIssueRunSummaries(issue)))
    // Team-linked issues use active workspace membership, even if stale direct membership remains.
    await pool.query('INSERT INTO mikka_workspaces (id,"userId",name) VALUES ($1,$2,$3)',[workspace,owner,'Isolated run workspace'])
    await pool.query('INSERT INTO orvilo_teams (id,"workspaceId","userId",name,identifier) VALUES ($1,$2,$3,$4,$5)',[team,workspace,owner,'Run test','RUNTEST'])
    await pool.query('INSERT INTO orvilo_team_issues ("issueId","teamId","workspaceId","userId") VALUES ($1,$2,$3,$4)',[issue,team,workspace,owner])
    for (const id of [owner,viewer,removed]) await pool.query('INSERT INTO mikka_workspace_members ("workspaceId","userId",name,email,role,status) VALUES ($1,$2,$3,$4,$5,$6)',[workspace,id,'Member',`${id}@example.com`,'member','active'])
    assert.equal((await actAs(viewer,()=>listIssueRunSummaries(issue))).length,2)
    await pool.query('UPDATE mikka_workspace_members SET status=$3 WHERE "workspaceId"=$1 AND "userId"=$2',[workspace,removed,'suspended'])
    assert.deepEqual((await actAs(viewer,()=>listIssueRunSummaries(issue))).map(row=>row.id),[run])
    await assert.rejects(actAs(removed,()=>listIssueRunSummaries(issue)))
    await pool.query('DELETE FROM mikka_workspace_members WHERE "workspaceId"=$1 AND "userId"=$2',[workspace,viewer])
    await assert.rejects(actAs(viewer,()=>listIssueRunSummaries(issue)))
    for (const id of excessRuns) await pool.query('INSERT INTO agent_runs (id,"userId","issueId","agentId",status) VALUES ($1,$2,$3,$4,$5)', [id,owner,issue,agent,'succeeded'])
    const bounded = await actAs(owner, () => listIssueRunSummaries(issue))
    assert.equal(bounded.length, 20)
    assert.ok(bounded.every(row => row.ownedByCurrentUser && row.id !== otherRun && row.id !== removedRun))
  } finally {
    await pool.query('DELETE FROM run_chunks WHERE "runId"=ANY($1::uuid[])',[[run,removedRun,otherRun,...excessRuns]])
    await pool.query('DELETE FROM agent_runs WHERE id=ANY($1::uuid[])',[[run,removedRun,otherRun,...excessRuns]])
    await pool.query('DELETE FROM agents WHERE id=$1',[agent])
    await pool.query('DELETE FROM issue_members WHERE "issueId"=ANY($1::uuid[])',[[issue,other]])
    await pool.query('DELETE FROM orvilo_team_issues WHERE "issueId"=$1',[issue])
    await pool.query('DELETE FROM orvilo_teams WHERE id=$1',[team])
    await pool.query('DELETE FROM mikka_workspace_members WHERE "workspaceId"=$1',[workspace])
    await pool.query('DELETE FROM mikka_workspaces WHERE id=$1',[workspace])
    await pool.query('DELETE FROM issues WHERE id=ANY($1::uuid[])',[[issue,other]])
    await pool.query('DELETE FROM "user" WHERE id=ANY($1::text[])',[[owner,viewer,outsider,removed]])
    await pool.end()
  }
})
