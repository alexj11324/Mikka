import { randomUUID } from 'node:crypto'
import { test, expect, register, app } from './fixtures'

test('未登录访问受保护页面、注册和登录链接', async ({ page }) => {
  await page.goto(app('/settings/members'))
  await expect(page).toHaveURL(/\/sign-in/)
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
  await page.getByRole('link', { name: '创建账号', exact: true }).last().click()
  await expect(page.getByRole('heading', { name: '创建你的工作账号' })).toBeVisible()
  await page.getByRole('link', { name: '去登录', exact: true }).last().click()
  await expect(page.getByRole('button', { name: '登录工作台', exact: true })).toBeVisible()
})

test('移动端设置菜单和工作区切换保持一致', async ({ page }) => {
  await page.setViewportSize({ width: 402, height: 874 })
  await register(page)
  const switcher = page.getByRole('button', { name: '工作区菜单', exact: true })
  const sidebar = page.locator('[data-slot="sidebar"][data-mobile="true"]')
  const toggle = page.getByRole('button', { name: '展开或收起侧栏', exact: true })
  async function openSidebar() {
    if (!await switcher.isVisible()) await toggle.click()
  }
  async function settings() {
    await openSidebar()
    await switcher.click()
    await page.getByRole('menuitem', { name: '设置', exact: true }).click()
    await expect(page.getByRole('heading', { name: '偏好设置', exact: true })).toBeVisible()
    await expect(sidebar).not.toBeVisible()
  }
  async function workspaces() {
    await openSidebar()
    await switcher.click()
    await page.getByRole('menuitem', { name: '切换工作区', exact: true }).click()
  }
  await settings()
  await openSidebar()
  await page.getByRole('link', { name: '返回工作台', exact: true }).click()
  await workspaces()
  await page.getByRole('menuitem', { name: '创建工作区', exact: true }).click()
  const name = `工作区回归 ${randomUUID()}`
  await page.getByLabel('工作区名称', { exact: true }).fill(name)
  await page.getByLabel('工作区网址', { exact: true }).fill(`mobile-${randomUUID().slice(0, 8)}`)
  await page.getByRole('button', { name: '创建工作区', exact: true }).click()
  await expect(page).toHaveURL(url => url.pathname === app('/'))
  await openSidebar()
  await expect(switcher).toContainText(name)
  await page.keyboard.press('Escape')
  await settings()
  await openSidebar()
  await page.getByRole('link', { name: '成员', exact: true }).click()
  await expect(page.getByRole('heading', { name: '成员', exact: true })).toBeVisible()
  await openSidebar()
  await page.getByRole('link', { name: '工作区', exact: true }).click()
  await expect(page.getByLabel('名称', { exact: true })).toHaveValue(name)
  await openSidebar()
  await page.getByRole('link', { name: '返回工作台', exact: true }).click()
  await workspaces()
  await page.getByRole('menuitem', { name: '回归测试成员的工作区', exact: true }).click()
  await expect(page.getByRole('heading', { name: '项目', exact: true })).toBeVisible()
  await openSidebar()
  await expect(switcher).toContainText('回归测试成员的工作区')
})

test('注册、创建任务、菜单、搜索、视图切换和退出登录', async ({ page }) => {
  const account = await register(page)
  await expect(page.getByRole('heading', { name: '项目', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '任务', exact: true }).click()
  await expect(page.getByRole('heading', { name: '全部任务', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '新建任务', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建任务', exact: true })
  await expect(dialog).toBeVisible()
  const title = `按钮回归 ${randomUUID()}`
  await dialog.getByLabel('任务标题', { exact: true }).fill(title)
  await dialog.getByRole('button', { name: /^任务状态/ }).click()
  await page.getByRole('menuitem', { name: '进行中', exact: true }).click()
  await dialog.getByRole('button', { name: '创建任务', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('region', { name: '任务看板', exact: true }).getByText(title, { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '任务', exact: true }).click()
  await expect(page.getByRole('region', { name: '任务看板', exact: true }).getByText(title, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '列表视图', exact: true }).click()
  await expect(page.locator('[aria-label="任务列表"]').getByRole('button').filter({ hasText: title })).toBeVisible()
  await page.getByRole('button', { name: '打开全局搜索', exact: true }).click()
  await page.getByRole('dialog', { name: '搜索任务', exact: true }).getByRole('combobox', { name: '全局搜索任务', exact: true }).fill(title)
  await page.getByRole('option').filter({ hasText: title }).click()
  await expect(page.getByLabel('任务标题', { exact: true })).toHaveValue(title)
  await expect(page.getByRole('button', { name: '账户菜单', exact: true })).toHaveCount(0)
  await expect(page.locator('[data-slot="sidebar-footer"]')).toHaveCount(0)
  await page.getByRole('button', { name: '工作区菜单', exact: true }).click()
  await page.getByRole('menuitem', { name: '切换工作区', exact: true }).hover()
  const switcher = page.getByRole('menu', { name: '切换工作区', exact: true })
  await expect(switcher).toContainText(account.email)
  await expect(switcher.getByRole('menuitem', { name: '创建工作区', exact: true })).toBeVisible()
  await expect(switcher.getByRole('menuitem', { name: '添加账户', exact: true })).toBeVisible()
  await expect(switcher.getByRole('menuitem', { name: '个人资料', exact: true })).toHaveCount(0)
  await expect(switcher.getByRole('menuitem', { name: '切换明暗主题', exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '工作区菜单', exact: true }).click()
  await page.getByRole('menuitem', { name: '退出登录', exact: true }).click()
  await expect(page).toHaveURL(/\/sign-in/)
  await page.getByLabel('邮箱', { exact: true }).fill(account.email)
  await page.getByLabel('密码', { exact: true }).fill(account.password)
  await page.getByRole('button', { name: '登录工作台', exact: true }).click()
  await expect(page).toHaveURL(url => url.pathname === app('/'))
  await page.getByRole('button', { name: '任务', exact: true }).click()
  await expect(page.getByRole('region', { name: '任务看板', exact: true }).getByText(title, { exact: true })).toBeVisible()
})
