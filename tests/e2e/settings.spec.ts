import { test, expect, register } from './fixtures'

test('成员与团队共用设置侧栏，创建居中弹窗，返回团队主页并往返设置', async ({ page }, testInfo) => {
  await register(page, '/settings/teams')
  const sidebar = page.locator('[data-slot="sidebar-container"]')
  await expect(sidebar).toHaveCount(1)
  await expect(page.getByRole('main')).toHaveCount(1)
  await sidebar.getByRole('link', { name: '成员', exact: true }).click()
  await expect(page.getByRole('heading', { name: '成员', exact: true })).toBeVisible()
  await expect(sidebar).toHaveCount(1)
  await sidebar.getByRole('link', { name: '偏好设置', exact: true }).click()
  await expect(page.getByRole('group', { name: '界面主题', exact: true })).toBeVisible()
  await sidebar.getByRole('link', { name: '团队', exact: true }).click()
  await page.getByRole('button', { name: '新建团队', exact: true }).first().click()
  const dialog = page.getByRole('dialog', { name: '创建公开团队', exact: true })
  await expect(dialog).toBeVisible()
  const bounds = await dialog.boundingBox()
  const viewport = page.viewportSize()!
  expect(Math.abs(bounds!.x + bounds!.width / 2 - viewport.width / 2)).toBeLessThan(2)
  await dialog.getByLabel('团队名称', { exact: true }).fill('设置回归团队')
  await dialog.getByLabel('团队标识', { exact: true }).fill('SETTINGS')
  await dialog.getByLabel('团队简介', { exact: true }).fill('主页、设置与团队创建共享导航体系。')
  await dialog.getByRole('button', { name: '创建团队', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(sidebar.getByRole('link', { name: '设置回归团队', exact: true })).toBeVisible()
  await sidebar.getByRole('link', { name: '设置回归团队', exact: true }).click()
  await expect(page.getByRole('heading', { name: '设置回归团队', exact: true })).toBeVisible()
  await expect(page.getByLabel('团队标识', { exact: true })).toHaveValue('SETTINGS')
  await page.getByRole('link', { name: '返回团队主页', exact: true }).click()
  await expect(page.getByRole('heading', { name: '设置回归团队', exact: true })).toBeVisible()
  await expect(page.getByText('主页、设置与团队创建共享导航体系。', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: '团队资源', exact: true })).toBeVisible()
  await testInfo.attach('团队主页', { body: await page.screenshot({ path: '/tmp/agent-browser/team-home-production.png', fullPage: true }), contentType: 'image/png' })
  await expect(page.getByRole('tab', { name: '概览', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: /^成员/ }).click()
  await expect(page.getByRole('row').filter({ hasText: '负责人' })).toContainText('回归测试成员')
  await page.getByRole('link', { name: '团队设置', exact: true }).click()
  await expect(sidebar).toHaveCount(1)
  await expect(sidebar.getByRole('link', { name: '设置回归团队', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.reload()
  await expect(page.getByLabel('团队标识', { exact: true })).toHaveValue('SETTINGS')
  await sidebar.getByRole('link', { name: '创建团队', exact: true }).click()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page).not.toHaveURL(/create=1/)
  await sidebar.getByRole('link', { name: '创建团队', exact: true }).click()
  await expect(dialog).toBeVisible()
})

test('移动端共用抽屉导航，团队弹窗不横向溢出并保护未保存内容', async ({ page }) => {
  await register(page, '/settings/teams')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '新建团队', exact: true }).first().click()
  const dialog = page.getByRole('dialog', { name: '创建公开团队', exact: true })
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  await dialog.getByLabel('团队名称', { exact: true }).fill('未保存的团队')
  page.once('dialog', confirmation => confirmation.dismiss())
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog.getByLabel('团队名称', { exact: true })).toHaveValue('未保存的团队')
  page.once('dialog', confirmation => confirmation.accept())
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: '展开或收起侧栏', exact: true }).click()
  const navigation = page.getByRole('dialog')
  await expect(navigation.getByRole('link', { name: '成员', exact: true })).toBeVisible()
  await navigation.getByRole('link', { name: '成员', exact: true }).click()
  await expect(navigation).not.toBeVisible()
  await expect(page.getByRole('heading', { name: '成员', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
